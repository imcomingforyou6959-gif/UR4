    for _, item in ipairs(children) do
        if item.Name == "[Stim]" and item:FindFirstChild("ClickDetector") then
            return item
        end
    end
    
    for _, item in ipairs(children) do
        if item.Name:find("Stim") and item:FindFirstChild("ClickDetector") then
            return item
