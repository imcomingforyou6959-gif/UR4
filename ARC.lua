local function get_weapon_parts(weapon)
    local parts = {}
    if not weapon then return parts end
    for _, d in ipairs(weapon:GetDescendants()) do
        if d:IsA("BasePart") then
            local skip = false
            local p = d
            while p and p ~= weapon do
                if p.Name == "CSSArms" or p.Name == "Arms" then skip = true; break end
                p = p.Parent
            end
            if not skip then table.insert(parts, d) end
        end
    end
    return parts
end

local weapon_saved = {}
local tracked_weapon = nil

local function save_weapon_part(part)
    if weapon_saved[part] then return end
    weapon_saved[part] = { color = part.Color, material = part.Material,
        reflectance = part.Reflectance, ltm = part.LocalTransparencyModifier }
end

local function restore_weapon_part(part)
    local orig = weapon_saved[part]
    if not orig then return end
    pcall(function()
        part.Color = orig.color; part.Material = orig.material
        part.Reflectance = orig.reflectance; part.LocalTransparencyModifier = orig.ltm
    end)
    weapon_saved[part] = nil
end

local function restore_all_weapon()
    for part, _ in pairs(weapon_saved) do restore_weapon_part(part) end
    weapon_saved = {}
end

local function apply_weapon_mods()
    local weapon = get_active_weapon()
    if not weapon then return end
    local parts = get_weapon_parts(weapon)
    if #parts == 0 then return end
    for _, part in ipairs(parts) do
        save_weapon_part(part)
        pcall(function()
            if S.gun_color then part.Color = S.gun_color_value end
            if S.gun_material then
                local m = Enum.Material[S.gun_material_value]
                if m then part.Material = m end
            end
            if S.gun_reflectance then part.Reflectance = S.gun_reflectance_value end
            if S.gun_ghost then part.LocalTransparencyModifier = S.gun_ghost_trans end
        end)
    end
end

